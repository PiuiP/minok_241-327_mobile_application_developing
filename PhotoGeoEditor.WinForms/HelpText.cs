namespace PhotoGeoEditor.WinForms;

/// <summary>Текст справки, который открывается по F1.</summary>
internal static class HelpText
{
    public const string Full = """
        PhotoGeoEditor — просмотр и редактор положения фотографий на карте по EXIF

        КАК РАБОТАТЬ
          1. Ctrl+O — открыть папку с фотографиями. На карте появятся миниатюры
             снимков, у которых в EXIF есть GPS-координаты.
             Красная стрелка у миниатюры — направление съёмки (азимут камеры).
          2. Выберите фото в списке слева или щёлкните по миниатюре на карте —
             справа откроются данные EXIF.
          3. Чтобы изменить положение:
               - перетащите миниатюру мышкой на новое место, или
               - введите координаты справа и нажмите Enter / «Применить».
          4. Фото без координат: выберите его в списке и щёлкните ПРАВОЙ кнопкой
             мыши по нужной точке карты (или нажмите «В центр карты»).
          5. Ctrl+E — записать изменения в EXIF. Режим записи выбирается в меню
             «Настройки»: копии в подпапку geo_edited (безопасно) или перезапись
             оригиналов.
          6. Ctrl+S / Ctrl+L — сохранить / загрузить СОСТОЯНИЕ приложения
             (файл *.pgeo.json): список фото, ваши правки, положение карты.

        ПОЛЯ EXIF
          Широта, долгота — градусы, например 55.753900 (минус: юг / запад)
          Высота — метры над уровнем моря
          Направление — азимут камеры, 0..360, по часовой стрелке от севера
          Время GPS — дата и время определения координат (UTC)
          Способ — как определена позиция: GPS, WLAN, MANUAL ...
          Система координат — обычно WGS-84

        ГОРЯЧИЕ КЛАВИШИ
          F1               эта справка
          Ctrl+O           открыть папку
          Ctrl+Shift+O     добавить файлы
          Ctrl+S           сохранить состояние (проект)
          Ctrl+L           загрузить состояние (проект)
          Ctrl+E           записать изменения в EXIF
          Ctrl+Shift+E     экспорт в GeoJSON / CSV
          Ctrl+R           вернуть исходные координаты выбранного фото
          Ctrl+0           показать на карте все фото
          Ctrl+T           переключить светлую / тёмную тему
          Delete           убрать выбранное фото из списка (в списке)
          Enter            применить значения из полей справа

        КАРТА
          колесо мыши — масштаб, перетаскивание фона — сдвиг карты,
          двойной щелчок — приблизить, перетаскивание миниатюры — новая позиция,
          правая кнопка — поставить выбранное фото в эту точку.

        ПАРАМЕТРЫ КОМАНДНОЙ СТРОКИ (графическое приложение)
          PhotoGeoEditor.Gui.exe [папка | файл.jpg | проект.pgeo.json] [--dark] [--help]

        КОНСОЛЬНАЯ ВЕРСИЯ (тот же код библиотеки PhotoGeoEditor.Core)
          PhotoGeoEditor list | show | set | clear | export | generate | state
          Подробности: PhotoGeoEditor --help
        """;
}
